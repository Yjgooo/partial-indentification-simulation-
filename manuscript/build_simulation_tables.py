#!/usr/bin/env python3
"""Generate manuscript tables directly from archived simulation summaries."""
from pathlib import Path
import csv
import json
import sys

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "vendor"))
from finite_support_engine import make_smooth_dgp  # noqa: E402


def read_rows(path):
    with path.open(newline="") as stream:
        return list(csv.DictReader(stream))


def number(row, key):
    return float(row[key])


def n_label(row):
    return f"{int(row['n']):,}"


def write(name, content):
    target = HERE / "tables" / name
    target.parent.mkdir(exist_ok=True)
    target.write_text("% Generated by build_simulation_tables.py; do not edit.\n" + content)


def table(caption, label, spec, header, rows, note=""):
    return (
        "\\begin{table}[!htbp]\n\\centering\n\\small\n"
        + "\\caption{" + caption + "}\\label{" + label + "}\n"
        + "\\begin{tabular}{" + spec + "}\n\\toprule\n"
        + header + " \\\\\n\\midrule\n"
        + "\n".join(row + " \\\\" for row in rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
        + ("\\par\\smallskip\n\\begin{minipage}{\\linewidth}\\footnotesize " + note + "\\end{minipage}\n" if note else "")
        + "\\end{table}\n"
    )


def main():
    designs = [
        ("Design 1, $K=2$", read_rows(ROOT / "small_sample_extension/regular_K2/combined_summary.csv")),
        ("Design 1, $K=4$", read_rows(ROOT / "small_sample_extension/regular_K4/combined_summary.csv")),
        ("Design 1, $K=16$", read_rows(ROOT / "small_sample_extension/regular_K16/combined_summary.csv")),
        ("Design 2, $K=4$", read_rows(ROOT / "small_sample_extension/boundary_K4/combined_summary.csv")),
    ]
    for _, rows in designs:
        assert [int(r["n"]) for r in rows] == [250, 1000, 4000, 16000, 64000, 256000, 1024000]
        assert all(int(r["repetitions"]) == 1500 for r in rows)
        assert all(number(r, "success_rate") == number(r, "coherent_rate") == 1 for r in rows)

    bounds = json.loads((ROOT / "support_size_study/population_bounds.json").read_text())
    id_rows = []
    for k in (2, 4, 16):
        d = bounds[str(k)]
        prefix = "" if k == 2 else r"$\geq$ "
        id_rows.append(
            f"{k} & $[{d['aux_lower']:.4f},{d['aux_upper']:.4f}]$ & {d['aux_width']:.4f}"
            f" & $[{d['noaux_lower']:.4f},{d['noaux_upper']:.4f}]$ & "
            + prefix + f"{100 * d['width_reduction_fraction_best_found']:.1f}\\%"
        )
    write("identification.tex", table(
        "Population identification under Design 1.", "tab:sim-identification",
        "rcccc", "$K$ & With auxiliary data & Width & Without auxiliary data & Reduction",
        id_rows
    ))

    rate_rows = []
    for name, rows in designs:
        log_n = np.log([int(r["n"]) for r in rows])
        slopes = [-np.polyfit(log_n, np.log([number(r, key) for r in rows]), 1)[0]
                  for key in ("lower_rmse", "upper_rmse", "joint_q95")]
        rate_rows.append(name + " & " + " & ".join(f"{s:.3f}" for s in slopes))
    write("rates.tex", table(
        "Estimated rate exponents.", "tab:sim-rates",
        "lrrr", r"Design & \shortstack{Lower-endpoint\\rate} & \shortstack{Upper-endpoint\\rate} & \shortstack{Joint-error\\rate}",
        rate_rows
    ))

    d = make_smooth_dgp(4)
    q_rows = [f"{a} & {y} & " + " & ".join(f"{v:.8f}" for v in d.q[a, y])
              for a in range(2) for y in range(2)]
    write("clean_q.tex", table(
        "Clean conditional probabilities $q_{ayk}$ for $K=4$.", "tab:sim-clean-q",
        "rrrrrr", "$a$ & $y$ & $k=1$ & $k=2$ & $k=3$ & $k=4$", q_rows
    ))

    full = [
        r"\begingroup\small\setlength{\tabcolsep}{4pt}",
        r"\begin{longtable}{lrrrrrr}",
        r"\caption{Estimation error and direct-LP feasibility by sample size.}\label{tab:sim-full-errors}\\",
        r"\toprule Design / $n=N$ & \shortstack{Lower\\bias} & \shortstack{Upper\\bias} & \shortstack{Lower\\RMSE} & \shortstack{Upper\\RMSE} & \shortstack{95th pct.\\joint error} & Feasible \\",
        r"\midrule\endfirsthead",
        r"\multicolumn{7}{l}{\textit{Table \thetable\ continued}}\\",
        r"\toprule Design / $n=N$ & \shortstack{Lower\\bias} & \shortstack{Upper\\bias} & \shortstack{Lower\\RMSE} & \shortstack{Upper\\RMSE} & \shortstack{95th pct.\\joint error} & Feasible \\",
        r"\midrule\endhead",
        r"\bottomrule\endfoot",
    ]
    for name, rows in designs:
        full.append(r"\multicolumn{7}{l}{\textit{" + name + r"}}\\*")
        for row_index, row in enumerate(rows):
            full.append(n_label(row) + " & " + " & ".join(
                f"{number(row, key):.6f}" for key in
                ("lower_bias", "upper_bias", "lower_rmse", "upper_rmse", "joint_q95"))
                + f" & {100 * number(row, 'raw_feasibility_rate'):.2f}\\%"
                + (r" \\*" if row_index < len(rows) - 1 else r" \\"))
        full.append(r"\addlinespace")
    full.extend([r"\end{longtable}", r"\endgroup"])
    # Keep each design's seven sample sizes together across page breaks.
    write("full_errors.tex", "\n".join(full) + "\n")

    boundary_rows = []
    for row in designs[-1][1]:
        boundary_rows.append(n_label(row) + f" & {100 * number(row, 'raw_feasibility_rate'):.2f}\\% & "
                             + " & ".join(f"{number(row, key):.3f}" for key in
                               ("scaled_lower_rmse", "scaled_upper_rmse", "scaled_joint_q95", "scaled_mean_endpoint_slack")))
    write("boundary_details.tex", table(
        "Design 2: feasibility, scaled errors, and constraint slack.", "tab:sim-boundary-details",
        "rrrrrr", r"$n=N$ & Feasible & \shortstack{$\sqrt n$\\lower RMSE} & \shortstack{$\sqrt n$\\upper RMSE} & \shortstack{$\sqrt n$\\95th pct. $d_H$} & $\sqrt n\,\overline S$",
        boundary_rows
    ))
    print("Validated four configurations and generated five LaTeX tables from archived summaries.")


if __name__ == "__main__":
    main()
